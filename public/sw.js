const CACHE_NAME = 'mono-studio-assets-v1';
const PRECACHE_ASSETS = [
  '/models/pullover_hoodie.glb',
  '/models/pose_landmarker_lite.task',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => {
      return cache.addAll(PRECACHE_ASSETS).catch((err) => {
        console.warn('ServiceWorker precache partial skip:', err);
      });
    })
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(
        keys.map((key) => {
          if (key !== CACHE_NAME) return caches.delete(key);
        })
      );
    })
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);

  // Cache-first strategy for heavy 3D models and AI task weights
  if (
    url.pathname.startsWith('/models/') ||
    url.pathname.endsWith('.glb') ||
    url.pathname.endsWith('.usdz') ||
    url.pathname.endsWith('.task') ||
    url.pathname.endsWith('.wasm')
  ) {
    event.respondWith(
      caches.match(event.request).then((cached) => {
        if (cached) return cached;
        return fetch(event.request).then((response) => {
          if (response && response.status === 200) {
            const clone = response.clone();
            caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone));
          }
          return response;
        });
      })
    );
  }
});
